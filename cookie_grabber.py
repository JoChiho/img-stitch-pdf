"""内置「获取 Cookies」：用工具自己的浏览器配置文件登录网站，经 CDP 导出 Netscape cookies.txt。

为什么不直接读 Chrome/Edge 的 Cookie 数据库：浏览器运行时数据库被锁，且 v127 起使用
App-Bound 加密（yt-dlp 报 ``Could not copy Chrome cookie database`` / DPAPI 错误）；
Chrome 136+ 也禁止在**默认**用户数据目录上开 ``--remote-debugging-port``。

做法：以 ``--user-data-dir=<工具文件夹>\\browser_profile`` 单独启动已安装的 Chrome/Edge
（与用户平时的浏览器配置完全隔离，不碰、不关闭用户的浏览器窗口），用户首次在该窗口登录；
之后通过 DevTools 协议（标准库实现的最小 WebSocket 客户端）调用 ``Storage.getCookies``，
按网站域名过滤，写成 ``cookies\\<网站>.txt``（原子写入），再 ``Browser.close`` 关闭该浏览器。

Cookie 值只写入文件，从不打印/记录到日志。无 Tk 依赖，可单元测试。
"""
from __future__ import annotations

import base64
import json
import os
import socket
import struct
import subprocess
import sys
import time
from pathlib import Path
from typing import Callable, Dict, Iterable, List, Mapping, Optional, Sequence, Tuple
from urllib.parse import urlsplit

import video_dl

PROFILE_DIRNAME = "browser_profile"
DEVTOOLS_PORT_FILE = "DevToolsActivePort"


class CookieGrabError(Exception):
    """中文错误信息（不含 cookie 值）。"""


# ---------------------------------------------------------------- sites
class SiteSpec:
    def __init__(self, key: str, login_url: str, domains: Sequence[str],
                 auth_cookies: Sequence[str] = (), label: str = "") -> None:
        self.key = key  # stored file name stem: cookies\<key>.txt
        self.login_url = login_url
        self.domains = tuple(domains)
        self.auth_cookies = tuple(auth_cookies)  # any present → logged in
        self.label = label or key


SITES: Dict[str, SiteSpec] = {
    "youtube": SiteSpec(
        "youtube.com", "https://www.youtube.com/",
        ("youtube.com", "google.com"),
        ("SAPISID", "__Secure-3PSID", "LOGIN_INFO"), "YouTube",
    ),
    "x": SiteSpec(
        "x.com", "https://x.com/login", ("x.com", "twitter.com"), ("auth_token",), "X (Twitter)",
    ),
}


def resolve_site(target: str) -> SiteSpec:
    """``youtube`` / ``x`` / 任意 URL → :class:`SiteSpec`。"""
    t = (target or "").strip()
    low = t.lower()
    if low in SITES:
        return SITES[low]
    if low in ("twitter", "x.com", "twitter.com"):
        return SITES["x"]
    if low in ("yt", "youtube.com"):
        return SITES["youtube"]
    url = t if "://" in t else "https://" + t
    key = video_dl.site_for_url(url)
    if not key or "." not in key:
        raise CookieGrabError(f"无法识别网站：{t!r}（请输入 youtube、x 或完整网址）")
    for spec in SITES.values():
        if spec.key == key:
            return spec
    return SiteSpec(key, url, (key,), (), key)


def domain_matches(cookie_domain: str, domains: Iterable[str]) -> bool:
    d = (cookie_domain or "").strip().lower().lstrip(".")
    if not d:
        return False
    for base in domains:
        b = base.strip().lower().lstrip(".")
        if d == b or d.endswith("." + b):
            return True
    return False


def filter_cookies(cookies: Iterable[Mapping], domains: Iterable[str]) -> List[Mapping]:
    doms = tuple(domains)
    return [c for c in cookies if domain_matches(str(c.get("domain", "")), doms)]


def is_logged_in(cookies: Iterable[Mapping], spec: SiteSpec) -> Optional[bool]:
    """True/False；网站没有已知登录 Cookie 名时为 None（无法判断）。"""
    if not spec.auth_cookies:
        return None
    names = {str(c.get("name", "")) for c in cookies}
    return any(n in names for n in spec.auth_cookies)


# ---------------------------------------------------------------- Netscape
def cdp_cookie_to_netscape(c: Mapping) -> Optional[str]:
    """CDP ``Network.Cookie`` dict → one Netscape line (None if unusable)."""
    domain = str(c.get("domain", "")).strip()
    name = str(c.get("name", ""))
    value = str(c.get("value", ""))
    if not domain or not name or any(ch in s for s in (domain, name, value) for ch in "\t\r\n"):
        return None
    flag = "TRUE" if domain.startswith(".") else "FALSE"
    path = str(c.get("path") or "/")
    secure = "TRUE" if c.get("secure") else "FALSE"
    expires = c.get("expires")
    try:
        exp = int(float(expires)) if expires is not None else 0
    except (TypeError, ValueError):
        exp = 0
    if c.get("session") or exp <= 0:
        exp = 0
    prefix = video_dl.HTTPONLY_PREFIX if c.get("httpOnly") else ""
    return "\t".join((prefix + domain, flag, path, secure, str(exp), name, value))


def cookies_to_netscape(cookies: Iterable[Mapping]) -> Tuple[str, int]:
    lines = [video_dl.NETSCAPE_HEADER,
             "# Generated by img-stitch-pdf (get_cookies). Contains login credentials: do not share.", ""]
    n = 0
    seen = set()
    for c in sorted(cookies, key=lambda c: (str(c.get("domain", "")), str(c.get("path", "")), str(c.get("name", "")))):
        line = cdp_cookie_to_netscape(c)
        if line is None:
            continue
        k = tuple(line.split("\t")[i] for i in (0, 2, 5))
        if k in seen:
            continue
        seen.add(k)
        lines.append(line)
        n += 1
    return "\n".join(lines) + "\n", n


# ---------------------------------------------------------------- browser detection
def browser_candidates(env: Optional[Mapping[str, str]] = None) -> List[Tuple[str, Path]]:
    e = os.environ if env is None else env
    out: List[Tuple[str, Path]] = []
    if sys.platform == "win32" or env is not None:
        roots = [e.get("PROGRAMFILES"), e.get("PROGRAMFILES(X86)"), e.get("LOCALAPPDATA")]
        for name, rel in (("chrome", r"Google\Chrome\Application\chrome.exe"),
                          ("edge", r"Microsoft\Edge\Application\msedge.exe")):
            for r in roots:
                if r:
                    out.append((name, Path(r) / rel))
    if sys.platform == "darwin" and env is None:
        out += [("chrome", Path("/Applications/Google Chrome.app/Contents/MacOS/Google Chrome")),
                ("edge", Path("/Applications/Microsoft Edge.app/Contents/MacOS/Microsoft Edge"))]
    elif sys.platform.startswith("linux") and env is None:
        out += [("chrome", Path("/usr/bin/google-chrome")), ("chrome", Path("/usr/bin/chromium")),
                ("edge", Path("/usr/bin/microsoft-edge"))]
    return out


def find_browsers(env: Optional[Mapping[str, str]] = None,
                  exists: Callable[[Path], bool] = lambda p: p.is_file()) -> List[Tuple[str, Path]]:
    """Installed Chrome/Edge, Chrome first; one entry per browser name."""
    found: Dict[str, Path] = {}
    for name, p in browser_candidates(env):
        if name not in found and exists(p):
            found[name] = p
    return [(n, found[n]) for n in ("chrome", "edge") if n in found]


def pick_browser(preferred: Optional[str] = None, env=None, exists=None) -> Tuple[str, Path]:
    kw = {} if exists is None else {"exists": exists}
    found = find_browsers(env, **kw)
    if not found:
        raise CookieGrabError("没有找到 Chrome 或 Edge。请安装其中之一后重试。")
    if preferred:
        for n, p in found:
            if n == preferred:
                return n, p
    return found[0]


def tool_profile_dir() -> Path:
    """``<工具文件夹>\\browser_profile``（工具专用浏览器配置；已在 .gitignore 中排除）。"""
    return Path(__file__).resolve().parent / PROFILE_DIRNAME


def build_launch_args(browser: Path, profile: Path, url: str, *, headless: bool = False) -> List[str]:
    args = [str(browser), f"--user-data-dir={profile}", "--remote-debugging-port=0",
            "--no-first-run", "--no-default-browser-check", "--disable-background-networking"]
    if headless:
        args += ["--headless=new", "--disable-gpu", "--mute-audio"]
    args.append(url)
    return args


# ---------------------------------------------------------------- minimal WebSocket (RFC 6455) client
class _WebSocket:
    def __init__(self, url: str, timeout: float = 10.0) -> None:
        u = urlsplit(url)
        if u.scheme != "ws":
            raise CookieGrabError(f"不支持的调试地址：{url}")
        self.sock = socket.create_connection((u.hostname or "127.0.0.1", u.port or 80), timeout=timeout)
        key = base64.b64encode(os.urandom(16)).decode()
        path = u.path + ("?" + u.query if u.query else "")
        req = (f"GET {path} HTTP/1.1\r\nHost: {u.hostname}:{u.port}\r\nUpgrade: websocket\r\n"
               f"Connection: Upgrade\r\nSec-WebSocket-Key: {key}\r\nSec-WebSocket-Version: 13\r\n\r\n")
        self.sock.sendall(req.encode())
        buf = b""
        while b"\r\n\r\n" not in buf:
            chunk = self.sock.recv(4096)
            if not chunk:
                raise CookieGrabError("连接浏览器调试端口失败（握手被关闭）。")
            buf += chunk
        head, self._rest = buf.split(b"\r\n\r\n", 1)
        if b" 101 " not in head.split(b"\r\n", 1)[0]:
            raise CookieGrabError("连接浏览器调试端口失败（握手被拒绝）。")

    def _recv_exact(self, n: int) -> bytes:
        out = self._rest[:n]
        self._rest = self._rest[n:]
        while len(out) < n:
            chunk = self.sock.recv(max(65536, n - len(out)))
            if not chunk:
                raise CookieGrabError("浏览器调试连接已断开。")
            out += chunk
        if len(out) > n:
            self._rest = out[n:] + self._rest
            out = out[:n]
        return out

    def send_text(self, text: str) -> None:
        data = text.encode("utf-8")
        hdr = bytearray([0x81])
        n = len(data)
        if n < 126:
            hdr.append(0x80 | n)
        elif n < 65536:
            hdr.append(0x80 | 126)
            hdr += struct.pack(">H", n)
        else:
            hdr.append(0x80 | 127)
            hdr += struct.pack(">Q", n)
        mask = os.urandom(4)
        hdr += mask
        self.sock.sendall(bytes(hdr) + bytes(b ^ mask[i % 4] for i, b in enumerate(data)))

    def recv_text(self) -> str:
        parts: List[bytes] = []
        while True:
            b1, b2 = self._recv_exact(2)
            op = b1 & 0x0F
            n = b2 & 0x7F
            if n == 126:
                n = struct.unpack(">H", self._recv_exact(2))[0]
            elif n == 127:
                n = struct.unpack(">Q", self._recv_exact(8))[0]
            mask = self._recv_exact(4) if b2 & 0x80 else None
            payload = self._recv_exact(n) if n else b""
            if mask:
                payload = bytes(b ^ mask[i % 4] for i, b in enumerate(payload))
            if op == 0x8:
                raise CookieGrabError("浏览器关闭了调试连接。")
            if op == 0x9:  # ping → pong
                self.sock.sendall(bytes([0x8A, 0x80 | len(payload)]) + b"\0\0\0\0" + payload)
                continue
            if op in (0x1, 0x2, 0x0):
                parts.append(payload)
                if b1 & 0x80:
                    return b"".join(parts).decode("utf-8", "replace")

    def close(self) -> None:
        try:
            self.sock.close()
        except OSError:
            pass


class CDPConnection:
    def __init__(self, ws_url: str, timeout: float = 15.0) -> None:
        self.ws = _WebSocket(ws_url, timeout)
        self._id = 0

    def call(self, method: str, params: Optional[dict] = None) -> dict:
        self._id += 1
        mid = self._id
        self.ws.send_text(json.dumps({"id": mid, "method": method, "params": params or {}}))
        while True:
            msg = json.loads(self.ws.recv_text())
            if msg.get("id") == mid:
                if "error" in msg:
                    raise CookieGrabError(f"浏览器调试命令 {method} 失败：{msg['error'].get('message', '')}")
                return msg.get("result", {})

    def close(self) -> None:
        self.ws.close()


def read_devtools_port_file(profile: Path) -> Optional[str]:
    """``DevToolsActivePort`` → ``ws://127.0.0.1:<port><path>`` or None."""
    try:
        lines = (profile / DEVTOOLS_PORT_FILE).read_text(encoding="utf-8").split()
        port = int(lines[0])
        path = lines[1] if len(lines) > 1 else ""
    except (OSError, ValueError, IndexError):
        return None
    if not path.startswith("/devtools/browser"):
        return None
    return f"ws://127.0.0.1:{port}{path}"


def _probe(ws_url: str) -> bool:
    try:
        c = CDPConnection(ws_url, timeout=3)
        try:
            c.call("Browser.getVersion")
            return True
        finally:
            c.close()
    except (OSError, CookieGrabError, ValueError):
        return False


# ---------------------------------------------------------------- session
class ExportResult:
    def __init__(self, site: str, path: Path, count: int, logged_in: Optional[bool]) -> None:
        self.site, self.path, self.count, self.logged_in = site, path, count, logged_in

    def summary(self) -> str:
        msg = f"已导出 {self.site} 的 Cookies：{self.path.name}（{self.count} 条）"
        if self.logged_in is False:
            msg += "。⚠ 未检测到登录 Cookie：请先在专用浏览器窗口登录该网站后再导出"
        return msg


def save_site_cookies(spec: SiteSpec, cookies: Iterable[Mapping], store_dir=None, *,
                       allow_anonymous: bool = False) -> ExportResult:
    """未检测到登录 Cookie 时默认不保存（避免用未登录的 Cookies 覆盖已有文件）。"""
    sel = filter_cookies(cookies, spec.domains)
    if not allow_anonymous and sel and is_logged_in(sel, spec) is False:
        raise CookieGrabError(
            f"专用浏览器里还没有登录 {spec.label}（未找到登录 Cookie），未保存，已有文件保持不变。"
            "请点「登录并获取 Cookies…」在打开的窗口中登录后再导出。"
        )
    text, n = cookies_to_netscape(sel)
    if n == 0:
        raise CookieGrabError(
            f"专用浏览器里没有 {spec.label} 的 Cookies。请先在打开的窗口中访问并登录该网站，再导出。"
        )
    dest = video_dl.stored_cookies_path_for_site(spec.key, store_dir)
    try:
        video_dl._atomic_write(dest, text.encode("utf-8"))
    except OSError as e:
        raise CookieGrabError(f"无法保存 Cookies 文件：{dest}（{e.strerror or e}）") from None
    return ExportResult(spec.key, dest, n, is_logged_in(sel, spec))


class BrowserSession:
    """One tool-owned browser process on ``browser_profile`` with CDP enabled."""

    def __init__(self, profile: Optional[Path] = None, browser: Optional[str] = None,
                 log: Callable[[str], None] = lambda m: None) -> None:
        self.profile = Path(profile) if profile else tool_profile_dir()
        self.browser_pref = browser
        self.log = log
        self.proc: Optional[subprocess.Popen] = None
        self.ws_url: Optional[str] = None

    def attach_existing(self) -> bool:
        url = read_devtools_port_file(self.profile)
        if url and _probe(url):
            self.ws_url = url
            return True
        return False

    def start(self, url: str, *, headless: bool = False, timeout: float = 30.0) -> None:
        if self.attach_existing():
            self.log("专用浏览器已在运行，直接连接。")
            if not headless:
                self._open_tab(url)
            return
        name, exe = pick_browser(self.browser_pref)
        self.profile.mkdir(parents=True, exist_ok=True)
        try:
            (self.profile / DEVTOOLS_PORT_FILE).unlink()
        except OSError:
            pass
        kw: dict = {"stdout": subprocess.DEVNULL, "stderr": subprocess.DEVNULL, "stdin": subprocess.DEVNULL}
        if sys.platform == "win32":
            kw["creationflags"] = getattr(subprocess, "CREATE_NO_WINDOW", 0) if headless else 0
        self.log(f"启动 {'Chrome' if name == 'chrome' else 'Edge'}（专用配置：{self.profile}"
                 f"{'，无界面' if headless else ''}）…")
        self.proc = subprocess.Popen(build_launch_args(exe, self.profile, url, headless=headless), **kw)
        deadline = time.monotonic() + timeout
        while time.monotonic() < deadline:
            u = read_devtools_port_file(self.profile)
            if u and _probe(u):
                self.ws_url = u
                return
            if self.proc.poll() is not None and not u:
                raise CookieGrabError("浏览器启动后立即退出了（专用配置可能被另一个窗口占用）。")
            time.sleep(0.3)
        self.terminate()
        raise CookieGrabError("等待浏览器调试端口超时。")

    def _open_tab(self, url: str) -> None:
        try:
            c = CDPConnection(self.ws_url)  # type: ignore[arg-type]
            try:
                c.call("Target.createTarget", {"url": url})
            finally:
                c.close()
        except (OSError, CookieGrabError):
            pass

    def get_cookies(self) -> List[dict]:
        if not self.ws_url and not self.attach_existing():
            raise CookieGrabError("专用浏览器没有在运行。请先点「登录并获取 Cookies…」。")
        try:
            c = CDPConnection(self.ws_url)  # type: ignore[arg-type]
        except OSError as e:
            raise CookieGrabError(f"连接专用浏览器失败（窗口可能已被关闭）：{e}") from None
        try:
            return list(c.call("Storage.getCookies").get("cookies", []))
        finally:
            c.close()

    def close(self, wait: float = 10.0) -> None:
        if self.ws_url:
            try:
                c = CDPConnection(self.ws_url, timeout=5)
                try:
                    c.ws.send_text(json.dumps({"id": 999999, "method": "Browser.close"}))
                    time.sleep(0.2)
                finally:
                    c.close()
            except (OSError, CookieGrabError):
                pass
        self.ws_url = None
        if self.proc is not None:
            try:
                self.proc.wait(timeout=wait)
            except subprocess.TimeoutExpired:
                self.terminate()
        self.proc = None

    def terminate(self) -> None:
        p = self.proc
        if p is None or p.poll() is not None:
            return
        if sys.platform == "win32":
            subprocess.run(["taskkill", "/PID", str(p.pid), "/T", "/F"], capture_output=True,
                           creationflags=getattr(subprocess, "CREATE_NO_WINDOW", 0))
        else:
            p.kill()
        try:
            p.wait(timeout=5)
        except subprocess.TimeoutExpired:
            pass

    def export(self, spec: SiteSpec, store_dir=None, *, close: bool = True,
               allow_anonymous: bool = False) -> ExportResult:
        try:
            return save_site_cookies(spec, self.get_cookies(), store_dir, allow_anonymous=allow_anonymous)
        finally:
            if close:
                self.close()


def refresh_headless(spec: SiteSpec, store_dir=None, profile=None, browser=None,
                     log: Callable[[str], None] = lambda m: None, settle: float = 4.0,
                     allow_anonymous: bool = False) -> ExportResult:
    """「直接刷新」：无界面启动专用配置，打开网站让 Cookies 轮换后导出并关闭。"""
    s = BrowserSession(profile, browser, log)
    s.start(spec.login_url, headless=True)
    try:
        if s.proc is not None:
            time.sleep(settle)
        return s.export(spec, store_dir, close=s.proc is not None, allow_anonymous=allow_anonymous)
    finally:
        if s.proc is not None:
            s.close()
